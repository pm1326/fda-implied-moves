"""
Tests of the model on the history. Writes results/analysis.md and charts in results/.

  1. FACTOR TESTS   Does each candidate factor change the size of the move? With bootstrap
                    confidence intervals, so a difference from a handful of cases is not over-read.
  2. BACKTEST       Fit each version of the model on 2018-2022 only, then forecast 2023-2026,
                    which it has never seen. Also a walk-forward test, one year at a time.
  3. SELLER'S RISK  What selling a straddle at a fair price would have looked like in each group.

Run build_history.py first.
"""
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

import model as M

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "results")
SPLIT = "2023-01-01"
rng = np.random.default_rng(7)


def load():
    h = pd.read_csv(os.path.join(HERE, "data", "history.csv"))
    h["abs"] = h["move_pct"].abs()
    h["runup"] = pd.cut(h["runup_20d_pct"], [-999, -10, 10, 9999], labels=["fell over 10%", "flat", "rose over 10%"]).astype(str)
    return h


def ci(x, n=2000):
    """Bootstrap 90% confidence interval for the mean."""
    x = np.asarray(x, float)
    if len(x) < 3:
        return (np.nan, np.nan)
    means = rng.choice(x, (n, len(x))).mean(axis=1)
    return tuple(np.percentile(means, [5, 95]).round(1))


def factor_table(df, by, title):
    rows = []
    for val, g in df.groupby(by):
        lo, hi = ci(g["abs"])
        rows.append({by: val, "decisions": len(g), "avg size of move %": round(g["abs"].mean(), 1),
                     "90% interval": f"{lo} to {hi}", "avg direction %": round(g["move_pct"].mean(), 1),
                     "avg multiple": round(g["multiple"].mean(), 2)})
    t = pd.DataFrame(rows)
    return f"**{title}**\n\n{t.to_markdown(index=False)}\n"


# ---------- Model versions, oldest to newest ----------

def v0(train):                       # flat average, ignores the share entirely
    m = train.groupby("outcome")["abs"].mean()
    return lambda r: m[r["outcome"]]


def v1(train):                       # one multiple per outcome, scaled by the share's own daily movement
    m = train.groupby("outcome")["multiple"].mean()
    return lambda r: m[r["outcome"]] * r["daily_vol_pct"]


def hard(train, cols, min_n=20):     # versions 2 and 3: group averages, falling back if under 20 examples
    def f(r):
        for depth in range(len(cols), -1, -1):
            g = train[train["outcome"] == r["outcome"]]
            for c in cols[:depth]:
                g = g[g[c] == r[c]]
            if len(g) >= min_n or depth == 0:
                return g["multiple"].mean() * r["daily_vol_pct"]
    return f


def shrunk(train, levels):           # version 4 onwards: the ladder with shrinkage in model.py
    table = M.fit(train, levels)
    return lambda r: M.predict(table, r["outcome"], r, levels)[0] * r["daily_vol_pct"]


VERSIONS = {
    "v0 flat average": v0,
    "v1 scaled by the share's normal movement": v1,
    "v2 + company size": lambda t: hard(t, ["size"]),
    "v3 + dependence on the drug": lambda t: hard(t, ["size", "dependence"]),
    "v3b same factors, shrinkage instead of a cut-off": lambda t: shrunk(t, {"approved": ["size", "dependence"], "rejected": ["size", "dependence"]}),
    "v4 + second attempt, reason for rejection": lambda t: shrunk(t, M.LEVELS),
    "v5 + share price run-up beforehand": lambda t: shrunk(t, {k: v + ["runup"] for k, v in M.LEVELS.items()}),
}


def score(train, test):
    rows = []
    for name, make in VERSIONS.items():
        f = make(train)
        pred = test.apply(f, axis=1).astype(float)
        err = pred - test["abs"]
        rows.append({"model": name, "avg error (points)": round(err.abs().mean(), 2),
                     "bias (points)": round(err.mean(), 2),
                     "rank correlation": round(pred.rank().corr(test["abs"].rank()), 3)})
    return pd.DataFrame(rows)


def main():
    os.makedirs(OUT, exist_ok=True)
    h = load()
    sm = h[h["size"].isin(["small", "mid"])]
    ap, rj = sm[sm["outcome"] == "approved"], sm[sm["outcome"] == "rejected"]
    md = ["# Analysis results", "",
          f"Generated by `analysis.py` from {len(h)} past FDA decisions. Do not edit by hand.", "",
          "## 1. Factor tests", "",
          "Small and mid-sized companies only, where decisions move the share. The 90% interval is a bootstrap "
          "range for the average: if two groups' intervals overlap heavily, the difference may be chance.", ""]
    md += [factor_table(sm[sm["outcome"] == "rejected"], "dependence", "Rejections, by dependence on the drug"),
           factor_table(rj, "reason", "Rejections, by the FDA's reason"),
           factor_table(rj[rj["dependence"] == "high"], "reason", "Rejections at one-product companies, by reason"),
           factor_table(ap, "second_attempt", "Approvals, by whether the drug was rejected before"),
           factor_table(ap, "new_molecule", "Approvals, by whether the drug is a new molecule"),
           factor_table(ap, "priority_review", "Approvals, by priority review"),
           factor_table(ap, "runup", "Approvals, by share price change in the month before"),
           factor_table(rj, "runup", "Rejections, by share price change in the month before")]

    # ---- Backtest ----
    train, test = h[h["date"] < SPLIT], h[h["date"] >= SPLIT]
    full = score(train, test)
    focus = score(train, test[test["size"].isin(["small", "mid"])])
    md += ["## 2. Out-of-sample backtest", "",
           f"Each model version is fitted on the {len(train)} decisions before 2023, then forecasts the size of the move for "
           f"the {len(test)} decisions from 2023 onwards. The outcome (approved or rejected) is taken as known, so this "
           "tests how well the model sizes the move, not whether it predicts the FDA.", "",
           "Average error is how far the forecast was from the actual move, in percentage points (lower is better). "
           "Rank correlation is whether the model puts decisions in the right order from small to large (higher is better).", "",
           "**All company sizes**", "", full.to_markdown(index=False), "",
           "**Small and mid-sized companies only**", "", focus.to_markdown(index=False), ""]

    # ---- Walk-forward ----
    parts = []
    for year in range(2021, 2027):
        tr, te = h[h["date"] < f"{year}-01-01"], h[(h["date"] >= f"{year}-01-01") & (h["date"] < f"{year + 1}-01-01")]
        te = te[te["size"].isin(["small", "mid"])]
        if len(te) < 5:
            continue
        for name, make in VERSIONS.items():
            f = make(tr)
            parts.append(pd.DataFrame({"model": name, "year": year, "pred": te.apply(f, axis=1).astype(float), "abs": te["abs"]}))
    wf = pd.concat(parts)
    wf["err"] = (wf["pred"] - wf["abs"]).abs()
    by_year = wf.pivot_table(index="model", columns="year", values="err", aggfunc="mean").round(2).reindex(list(VERSIONS))
    by_year["all years"] = wf.groupby("model")["err"].mean().round(2)
    md += ["## 3. Walk-forward test", "",
           "For each year, the model is fitted only on earlier years and then forecasts that year. Small and mid-sized "
           "companies. Average error in percentage points.", "", by_year.reset_index().to_markdown(index=False), ""]

    # ---- Seller's risk ----
    rows = []
    for (dep, out), g in sm.groupby(["dependence", "outcome"]):
        fair = g["abs"].mean()
        pnl = fair - g["abs"]            # sell a straddle at the average move, pay out the actual move
        rows.append({"dependence": dep, "outcome": out, "decisions": len(g), "fair price (avg move %)": round(fair, 1),
                     "seller wins %": round((pnl > 0).mean() * 100), "typical win (points)": round(pnl[pnl > 0].mean(), 1),
                     "typical loss (points)": round(pnl[pnl <= 0].mean(), 1), "worst loss (points)": round(pnl.min(), 1),
                     "95th percentile move %": round(g["abs"].quantile(0.95), 1)})
    md += ["## 4. What selling a straddle would have looked like", "",
           "If options were priced exactly at the historical average move, a seller would break even on average. "
           "This shows how that average is made up.", "", pd.DataFrame(rows).to_markdown(index=False), ""]

    with open(os.path.join(OUT, "analysis.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(md))

    # ---- Charts ----
    plt.rcParams.update({"font.size": 10, "axes.spines.top": False, "axes.spines.right": False})
    fig, ax = plt.subplots(figsize=(8, 4.5))
    groups = [("approved", "low"), ("approved", "high"), ("rejected", "low"), ("rejected", "high")]
    data = [sm[(sm["outcome"] == o) & (sm["dependence"] == d)]["move_pct"] for o, d in groups]
    ax.boxplot(data, vert=False, showfliers=True, flierprops={"markersize": 3})
    ax.set_yticks(range(1, 5), [f"{o}, {'one-product' if d == 'high' else 'has other products'} (n={len(x)})" for (o, d), x in zip(groups, data)])
    ax.axvline(0, color="grey", lw=0.8)
    ax.set_xlabel("Share price move across the decision (%)")
    ax.set_title("FDA decisions at small and mid-sized companies, 2018 to 2026")
    fig.tight_layout(); fig.savefig(os.path.join(OUT, "moves_by_dependence.png"), dpi=150); plt.close(fig)

    fig, ax = plt.subplots(figsize=(8, 4))
    ax.barh([n.split(" ")[0] for n in focus["model"]][::-1], focus["avg error (points)"][::-1], color="#2446c8")
    for i, v in enumerate(focus["avg error (points)"][::-1]):
        ax.text(v + 0.05, i, f"{v}", va="center")
    ax.set_xlabel("Average forecast error on 2023 to 2026 decisions (percentage points, lower is better)")
    ax.set_title("Out-of-sample error by model version (small and mid-sized companies)")
    fig.tight_layout(); fig.savefig(os.path.join(OUT, "backtest_error.png"), dpi=150); plt.close(fig)

    fig, ax = plt.subplots(figsize=(8, 4))
    hi = rj[rj["dependence"] == "high"]
    for reason, colour in [("clinical", "#c23b3b"), ("manufacturing", "#2446c8"), ("other", "#8a93a6")]:
        ax.hist(hi[hi["reason"] == reason]["move_pct"], bins=np.arange(-80, 31, 10), alpha=0.6, label=f"{reason} (n={(hi['reason'] == reason).sum()})", color=colour)
    ax.set_xlabel("Share price move (%)"); ax.set_ylabel("Decisions"); ax.legend(title="FDA's reason")
    ax.set_title("Rejections at one-product companies, by the FDA's reason")
    fig.tight_layout(); fig.savefig(os.path.join(OUT, "rejections_by_reason.png"), dpi=150); plt.close(fig)

    print("\n".join(md))


if __name__ == "__main__":
    main()
